#!/usr/bin/env node
// Writes the locale data the runtime carries because Puerts' V8 has no ICU, read from this Node's own ICU:
//   Runtime/src/tzData.ts      every IANA time zone's UTC offset changes from 2000 through 2040 (timeZones.ts)
//   Runtime/src/latinData.ts   the canonical decompositions of the Latin letters (textNormalize.ts, collation.ts)
// Run it again when a newer Node brings newer time zone rules:
//   node Runtime/scripts/generate-locale-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const src = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src');
const FIRST = 2000, LAST = 2040;

// Older names that are still in use for the same zones (the IANA "backward" links people still meet).
const ALIASES = ['UTC', 'GMT', 'Etc/UTC', 'Etc/GMT', 'Etc/Universal', 'Etc/Zulu', 'Universal', 'Zulu', 'Etc/Greenwich', 'Greenwich',
  'US/Eastern', 'US/Central', 'US/Mountain', 'US/Pacific', 'US/Alaska', 'US/Hawaii', 'US/Arizona', 'US/Michigan', 'US/Aleutian', 'US/East-Indiana',
  'Canada/Eastern', 'Canada/Central', 'Canada/Mountain', 'Canada/Pacific', 'Canada/Atlantic', 'Canada/Newfoundland',
  'Asia/Calcutta', 'Asia/Kolkata', 'Asia/Saigon', 'Asia/Ho_Chi_Minh', 'Asia/Katmandu', 'Asia/Kathmandu', 'Asia/Rangoon', 'Asia/Yangon',
  'Asia/Dacca', 'Asia/Dhaka', 'Asia/Ulan_Bator', 'Asia/Ulaanbaatar', 'Asia/Chongqing', 'Asia/Harbin', 'Asia/Macao', 'Asia/Thimbu', 'Asia/Ujung_Pandang',
  'Europe/Kiev', 'Europe/Kyiv', 'Europe/Belfast', 'Europe/Nicosia', 'Europe/Tiraspol', 'America/Buenos_Aires', 'America/Argentina/Buenos_Aires',
  'America/Indianapolis', 'America/Fort_Wayne', 'America/Louisville', 'America/Knox_IN', 'America/Godthab', 'America/Nuuk', 'America/Montreal',
  'America/Shiprock', 'America/Ensenada', 'America/Santa_Isabel', 'America/Coral_Harbour', 'America/Atka', 'America/Porto_Acre', 'America/Virgin',
  'Atlantic/Faeroe', 'Atlantic/Faroe', 'Africa/Asmera', 'Africa/Timbuktu', 'Pacific/Truk', 'Pacific/Ponape', 'Pacific/Samoa', 'Pacific/Enderbury',
  'Pacific/Kanton', 'Australia/ACT', 'Australia/NSW', 'Australia/Canberra', 'Australia/North', 'Australia/Queensland', 'Australia/South',
  'Australia/Tasmania', 'Australia/Victoria', 'Australia/West', 'Australia/Yancowinna', 'Australia/LHI', 'Brazil/East', 'Brazil/West',
  'Chile/Continental', 'Mexico/General', 'Mexico/BajaNorte', 'Mexico/BajaSur', 'NZ', 'NZ-CHAT', 'PRC', 'ROC', 'ROK', 'Japan', 'Singapore', 'Hongkong',
  'Israel', 'Iran', 'Egypt', 'Turkey', 'Poland', 'Portugal', 'GB', 'GB-Eire', 'Eire', 'Iceland', 'Jamaica', 'Cuba', 'Libya', 'Navajo', 'Kwajalein',
  'EST', 'MST', 'HST', 'EST5EDT', 'CST6CDT', 'MST7MDT', 'PST8PDT', 'CET', 'EET', 'MET', 'WET',
  ...Array.from({length: 27}, (_, i) => i - 14).filter(n => n !== 0).map(n => `Etc/GMT${n > 0 ? '+' : ''}${n}`)];

const valid = tz => { try { new Intl.DateTimeFormat('en-US', {timeZone: tz}); return true; } catch { return false; } };
const zones = [...new Set([...Intl.supportedValuesOf('timeZone'), ...ALIASES])].filter(valid).sort();

const fmts = new Map();
/** The zone's UTC offset in minutes at instant ms. */
function offset(tz, ms) {
  let f = fmts.get(tz);
  if (!f) fmts.set(tz, f = new Intl.DateTimeFormat('en-US', {timeZone: tz, hourCycle: 'h23', year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric'}));
  const p = {};
  for (const x of f.formatToParts(ms)) p[x.type] = Number(x.value);
  return Math.round((Date.UTC(p.year, p.month - 1, p.day, p.hour % 24, p.minute) - Math.floor(ms / 60000) * 60000) / 60000);
}

// Each zone: its offset at the start, then each change as minutes since the previous change and the new offset, all in
// base 36. Zones with the same history share one entry.
const start = Date.UTC(FIRST, 0, 1), end = Date.UTC(LAST + 1, 0, 1), WEEK = 7 * 864e5;
const rules = [], ruleIndex = new Map(), zoneRule = [];
for (const tz of zones) {
  let prev = offset(tz, start), last = start / 60000, s = prev.toString(36);
  for (let t = start; t < end; t += WEEK) {
    const next = Math.min(t + WEEK, end - 60000), o = offset(tz, next);
    if (o === prev) continue;
    let lo = t, hi = next;
    while (hi - lo > 60000) { const mid = Math.floor((lo + hi) / 120000) * 60000; if (offset(tz, mid) === prev) lo = mid; else hi = mid; }
    s += ',' + (hi / 60000 - last).toString(36) + ':' + o.toString(36);
    last = hi / 60000; prev = o;
  }
  if (!ruleIndex.has(s)) { ruleIndex.set(s, rules.length); rules.push(s); }
  zoneRule.push(`${tz}=${ruleIndex.get(s).toString(36)}`);
}
const zoneLines = [];
for (let i = 0; i < zoneRule.length; i += 40) zoneLines.push(JSON.stringify(zoneRule.slice(i, i + 40).join(' ')));
fs.writeFileSync(path.join(src, 'tzData.ts'), `/** Generated by Runtime/scripts/generate-locale-data.mjs from Node ${process.versions.node} (ICU ${process.versions.icu}, tz ${process.versions.tz}).
 *  Do not edit. Each zone names a rule; a rule is the UTC offset in minutes on ${FIRST}-01-01, then each change as
 *  "minutes since the previous change:new offset", in base 36. Changes run through ${LAST}. */
export const TZ_FIRST_YEAR = ${FIRST}, TZ_LAST_YEAR = ${LAST};
export const TZ_RULES: string[] = [
${rules.map(r => '  ' + JSON.stringify(r) + ',').join('\n')}
];
export const TZ_ZONES: string = [
${zoneLines.map(l => '  ' + l + ',').join('\n')}
].join(' ');
`);

// Latin letters with a canonical decomposition: Latin-1, Latin Extended-A and B, and Latin Extended Additional, plus
// the Latin ligatures, whose decomposition is a compatibility one (NFKD).
const canon = [], compat = [];
for (const [a, b] of [[0xc0, 0x24f], [0x1e00, 0x1eff]]) {
  for (let cp = a; cp <= b; cp++) { const ch = String.fromCodePoint(cp), d = ch.normalize('NFD'); if (d !== ch) canon.push(ch + d); }
}
for (let cp = 0xfb00; cp <= 0xfb06; cp++) { const ch = String.fromCodePoint(cp), d = ch.normalize('NFKD'); if (d !== ch) compat.push(ch + d); }
for (const ch of [' ', 'ª', '²', '³', '¹', 'º', '¼', '½', '¾', '…', '™']) compat.push(ch + ch.normalize('NFKD'));
fs.writeFileSync(path.join(src, 'latinData.ts'), `/** Generated by Runtime/scripts/generate-locale-data.mjs from Node ${process.versions.node} (ICU ${process.versions.icu}). Do not edit.
 *  Each entry is a character followed by its full decomposition, entries separated by "|". CANONICAL holds the Latin
 *  letters' canonical (NFD) decompositions, COMPAT the compatibility (NFKD) ones of ligatures and a few signs. */
export const CANONICAL = ${JSON.stringify(canon.join('|'))};
export const COMPAT = ${JSON.stringify(compat.join('|'))};
`);
console.log(`${zones.length} zones in ${rules.length} rules; ${canon.length} canonical and ${compat.length} compatibility decompositions`);
